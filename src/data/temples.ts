function aartis(times: [string, string, string, string], durations = [30, 25, 30, 25]): Aarti[] {
  return (['kakad', 'madhyan', 'dhoop', 'shej'] as const).map((key, i) => ({
    key,
    name: aartiMeta[key].name,
    sanskrit: aartiMeta[key].sanskrit,
    meaning: aartiMeta[key].meaning,
    time: times[i],
    duration: durations[i],
  }))
}

